package main

import (
	"encoding/json"
	"log"
	"os"
	"path/filepath"
	"time"

	"github.com/moby/buildkit-bench/util/gotest"
	"github.com/moby/buildkit-bench/util/testutil"
	"github.com/pkg/errors"
)

type genCmd struct {
	Files []string `kong:"arg='',name='files',required,help='Benchmark results files generated by parse command.'"`

	Name               string `kong:"name='name',help='Name of the report.'"`
	Config             string `kong:"name='config',required,default='testconfig.yml',help='Test config file.'"`
	HTMLOutput         string `kong:"name='html-output',default='./bin/gen/benchmarks.html',help='File to write the HTML report to.'"`
	JSONOutput         string `kong:"name='json-output',default='./bin/gen/benchmarks.json',help='File to write the versioned JSON report to.'"`
	Project            string `kong:"name='project',enum='buildkit,buildx',default='buildkit',help='Project type.'"`
	Candidates         string `kong:"name='candidates',help='Candidates file.'"`
	BuildkitCandidates string `kong:"name='buildkit-candidates',help='BuildKit candidates for JSON provenance.'"`
	BuildxCandidates   string `kong:"name='buildx-candidates',help='Buildx candidates for JSON provenance.'"`
	GHAEvent           string `kong:"name='gha-event',help='GitHub Actions payload JSON file.'"`
	Envs               string `kong:"name='envs',help='Environment variables file.'"`
	ValidationMode     string `kong:"name='validation-mode',enum='sloppy,strict',default='sloppy',help='Validation mode.'"`
}

func (c *genCmd) Run(ctx *Context) error {
	htmlPath, err := filepath.Abs(c.HTMLOutput)
	if err != nil {
		return err
	}
	jsonPath, err := filepath.Abs(c.JSONOutput)
	if err != nil {
		return err
	}
	if htmlPath == jsonPath {
		return errors.New("JSON and HTML output paths must differ")
	}
	benchmarks, err := gotest.MergeBenchmarks(c.Files)
	if err != nil {
		return err
	}
	if ctx.Debug {
		b, _ := json.MarshalIndent(benchmarks, "", "  ")
		log.Printf("%s", string(b))
	}
	if err := c.validateBenchmarks(benchmarks); err != nil {
		return err
	}
	report, err := c.jsonReport()
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(c.HTMLOutput), 0755); err != nil {
		return errors.Wrap(err, "failed to create output directory")
	}
	if err := c.writeHTML(benchmarks); err != nil {
		return err
	}
	return c.writeJSON(report)
}

func (c *genCmd) validateBenchmarks(benchmarks map[string]gotest.Benchmark) error {
	log.Printf("Validating %d benchmark results based on %s", len(benchmarks), c.Config)
	tc, err := testutil.LoadTestConfig(c.Config)
	if err != nil {
		return err
	}
	seen := make(map[string]struct{})
	for _, benchmark := range benchmarks {
		if _, ok := seen[benchmark.Name]; !ok {
			seen[benchmark.Name] = struct{}{}
		}
		bm, err := tc.BenchmarkConfig(benchmark.Name)
		if err != nil {
			return err
		}
		for _, run := range benchmark.Runs {
			for unit := range run.Extra {
				if _, ok := bm.Metrics[unit]; !ok {
					return errors.Errorf("unknown metric %q for benchmark %q", unit, benchmark.Name)
				}
			}
		}
	}
	if c.ValidationMode == "strict" {
		for rootName, bms := range tc.Runs {
			for testName, testConfig := range bms {
				if testConfig.Scope != "" && testConfig.Scope != c.Project {
					continue
				}
				if _, ok := seen[rootName+"/"+testName]; !ok {
					return errors.Errorf("missing benchmark result for %q", rootName+"/"+testName)
				}
			}
		}
	}
	return nil
}

func benchmarkMetricValues(run gotest.BenchmarkRun, bc *testutil.TestConfigBenchmark) (map[string]float64, error) {
	for metric := range run.Extra {
		if _, ok := bc.Metrics[metric]; !ok {
			return nil, errors.Errorf("unknown metric %q for run %s (buildx %s)", metric, run.Ref, run.Buildx)
		}
	}
	values := make(map[string]float64, len(bc.Metrics))
	for metric := range bc.Metrics {
		if value, ok := run.Extra[metric]; ok {
			values[metric] = value
		} else if metric == string(testutil.MetricDuration) {
			values[metric] = time.Duration(run.NsPerOp).Seconds()
		} else {
			return nil, errors.Errorf("missing metric %q for run %s (buildx %s)", metric, run.Ref, run.Buildx)
		}
	}
	return values, nil
}
